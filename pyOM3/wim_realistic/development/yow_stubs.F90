! Minimal stand-ins for the ecwam/fiat modules used by the IPHYS=0 source
! routines, so that they can be compiled unchanged for a column reference.
MODULE PARKIND1
  IMPLICIT NONE
  INTEGER, PARAMETER :: JPIM = SELECTED_INT_KIND(9)
  INTEGER, PARAMETER :: JPRB = SELECTED_REAL_KIND(13,300)
  INTEGER, PARAMETER :: JPRD = SELECTED_REAL_KIND(13,300)
END MODULE PARKIND1
MODULE PARKIND_WAVE
  USE PARKIND1, ONLY : JPIM, JPRB, JPRD
  IMPLICIT NONE
  INTEGER, PARAMETER :: JWIM = JPIM
  INTEGER, PARAMETER :: JWRB = JPRB
  INTEGER, PARAMETER :: JWRU = JPRD
END MODULE PARKIND_WAVE
MODULE YOMHOOK
  USE PARKIND1, ONLY : JPRB
  IMPLICIT NONE
  INTEGER, PARAMETER :: JPHOOK = JPRB
  LOGICAL :: LHOOK = .FALSE.
CONTAINS
  SUBROUTINE DR_HOOK(CDNAME, KSWITCH, PKEY)
    CHARACTER(LEN=*), INTENT(IN) :: CDNAME
    INTEGER, INTENT(IN) :: KSWITCH
    REAL(KIND=JPHOOK), INTENT(INOUT) :: PKEY
  END SUBROUTINE DR_HOOK
END MODULE YOMHOOK
