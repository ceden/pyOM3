! f2py entry points. The ecwam routines take their dimensions from module
! variables, which f2py cannot see, so each wrapper carries explicit
! dimensions and calls the unchanged ecwam routine.
!
! Spectral arrays are (KIJL,NANG,NFRE) in ecwam order; the python side
! passes Fortran-ordered arrays of that shape.

      SUBROUTINE W_SETUP(NA, NF, FR_IN, TH_IN, GRAV, ROA, ROW,        &
     &                   BETAMAX_IN, ZALP_IN, ALPHA_IN, CDIS_IN,      &
     &                   DELTA_IN, CDISVIS_IN, TAILF, TAILF_PM)
      USE PARKIND_WAVE, ONLY : JWIM, JWRB
      USE YOWPARAM , ONLY : NANG, NFRE
      USE YOWFRED  , ONLY : FR, TH, COSTH, SINTH, ZPIFR, FR5, DFIM,     &
     &                      DFIMOFR, DFIMFR, RHOWG_DFIM, DELTH, FRATIO, &
     &                      FLOGSPRDM1
      USE YOWPCONS , ONLY : G, GM1, PI, ZPI, ZPI4GM1, ZPI4GM2, ROAIR, ROWATER
      USE YOWPHYS  , ONLY : BETAMAX, ZALP, ALPHA, ALPHAMIN, CDIS,      &
     &                      DELTA_SDIS, CDISVIS, TAUWSHELTER,           &
     &                      TAILFACTOR, TAILFACTOR_PM, DELTA_THETA_RN
      IMPLICIT NONE
      INTEGER(KIND=JWIM), INTENT(IN) :: NA, NF
      REAL(KIND=JWRB), INTENT(IN) :: FR_IN(NF), TH_IN(NA)
      REAL(KIND=JWRB), INTENT(IN) :: GRAV, ROA, ROW
      REAL(KIND=JWRB), INTENT(IN) :: BETAMAX_IN, ZALP_IN, ALPHA_IN, CDIS_IN
      REAL(KIND=JWRB), INTENT(IN) :: DELTA_IN, CDISVIS_IN, TAILF, TAILF_PM
      INTEGER :: M, K
      REAL(KIND=JWRB) :: CO1, XLOGFRATIO
      NANG = NA
      NFRE = NF
      G = GRAV
      GM1 = 1.0_JWRB/G
      PI = ACOS(-1.0_JWRB)
      ZPI = 2.0_JWRB*PI
      ZPI4GM1 = ZPI**4/G
      ZPI4GM2 = ZPI**4/G**2
      ROAIR = ROA
      ROWATER = ROW
      BETAMAX = BETAMAX_IN
      ZALP = ZALP_IN
      ALPHA = ALPHA_IN
      ALPHAMIN = 0.0001_JWRB
      CDIS = CDIS_IN
      DELTA_SDIS = DELTA_IN
      CDISVIS = CDISVIS_IN
      TAUWSHELTER = 0.0_JWRB
      TAILFACTOR = TAILF
      TAILFACTOR_PM = TAILF_PM
      DELTA_THETA_RN = 0.75_JWRB
      IF (ALLOCATED(FR)) DEALLOCATE(FR, TH, COSTH, SINTH, ZPIFR, FR5,   &
     &                              DFIM, DFIMOFR, DFIMFR, RHOWG_DFIM)
      ALLOCATE(FR(NF), TH(NA), COSTH(NA), SINTH(NA), ZPIFR(NF), FR5(NF), &
     &         DFIM(NF), DFIMOFR(NF), DFIMFR(NF), RHOWG_DFIM(NF))
      FR = FR_IN
      TH = TH_IN
      FRATIO = FR(2)/FR(1)
      DELTH = ZPI/REAL(NA,JWRB)
      DO K=1,NA
        COSTH(K) = COS(TH(K))
        SINTH(K) = SIN(TH(K))
      ENDDO
      CO1 = 0.5_JWRB*(FRATIO-1.0_JWRB)*DELTH
      DFIM(1) = CO1*FR(1)
      DO M=2,NF-1
        DFIM(M) = CO1*(FR(M)+FR(M-1))
      ENDDO
      DFIM(NF) = CO1*FR(NF-1)
      DO M=1,NF
        DFIMOFR(M) = DFIM(M)/FR(M)
        DFIMFR(M)  = DFIM(M)*FR(M)
        ZPIFR(M) = ZPI*FR(M)
        FR5(M) = FR(M)**5
      ENDDO
      FLOGSPRDM1 = 1.0_JWRB/LOG10(FRATIO)
      XLOGFRATIO = LOG(FRATIO)
      RHOWG_DFIM(1) = 0.5_JWRB*ROWATER*G*DELTH*XLOGFRATIO*FR(1)
      DO M=2,NF-1
        RHOWG_DFIM(M) = ROWATER*G*DELTH*XLOGFRATIO*FR(M)
      ENDDO
      RHOWG_DFIM(NF) = 0.5_JWRB*ROWATER*G*DELTH*XLOGFRATIO*FR(NF)
      CALL INIT_X0TAUHF
      END SUBROUTINE W_SETUP

